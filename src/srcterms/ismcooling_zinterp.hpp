  // in between values of 1.0 < log(T) < 9.0
  // linear interpolation of tabulated cooling rate generated using Grackle
  int ipps  = static_cast<int>(100.0*logt) - 100;
  ipps = (ipps < 800)? ipps : 800;
  ipps = (ipps > 0 )? ipps : 0;
